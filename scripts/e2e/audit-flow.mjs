// Report → match → provider offer → survivor view, with screenshots at each step.
import fs from "node:fs";
import path from "node:path";
import { BASE, launch, newPage, signIn } from "./lib.mjs";
import { db, poll, matchesFor } from "./helpers.mjs";
const OUT = process.env.AUDIT_OUT || path.resolve("audit-out");
fs.mkdirSync(OUT, { recursive: true });
const started = new Date().toISOString();
const browser = await launch();
const phone = await newPage(browser, { viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const shot = async (pg, n, full = false) => { await pg.waitForTimeout(1800); await pg.screenshot({ path: path.join(OUT, `flow_${n}.png`), fullPage: full }); console.log("shot", n, new URL(pg.url()).pathname); };
await phone.goto(`${BASE}/report-abuse`, { waitUntil: "networkidle", timeout: 120000 });
await shot(phone, "01_report_empty", true);
await phone.getByRole("combobox", { name: /select incident types/i }).tap();
await phone.getByRole("option", { name: "Physical abuse" }).tap();
await shot(phone, "02_report_types_open");
await phone.getByRole("button", { name: /^Done/ }).tap();
await phone.getByText("select urgency").first().tap();
await phone.getByText("high urgency").first().tap();
await phone.getByRole("combobox", { name: /help you need/i }).tap();
await phone.getByRole("option", { name: "legal support" }).tap();
await phone.getByRole("option", { name: "medical care" }).tap();
await phone.getByRole("button", { name: /^Done/ }).tap();
await phone.getByText("select consent").first().tap();
await phone.getByText("I consent").first().tap();
await phone.getByPlaceholder(/share what happened/i).fill("UX audit report: needs legal and medical support.");
await phone.locator("#report-password").fill(`E2e-${Date.now()}-pw`);
await shot(phone, "03_report_filled", true);
await phone.getByRole("button", { name: /submit report/i }).tap();
await phone.waitForURL(/\/dashboard/, { timeout: 90000 });
await shot(phone, "04_survivor_after_submit");
const anon = await poll(async () => (await db.from("profiles").select("id").eq("is_anonymous", true).gte("created_at", started).limit(1)).data?.[0], { timeout: 30000 });
const rep = (await db.from("reports").select("*").eq("user_id", anon.id).single()).data;
const ms = await poll(async () => { const m = await matchesFor(rep.report_id); return m.length ? m : null; }, { timeout: 60000 });
console.log("matches", ms?.length);
await phone.goto(`${BASE}/dashboard/reports`, { waitUntil: "networkidle" });
await shot(phone, "05_survivor_reports");
await phone.goto(`${BASE}/dashboard/reports/${rep.report_id}`, { waitUntil: "networkidle" }).catch(() => {});
await shot(phone, "06_survivor_report_detail", true);
// provider
const pro = await newPage(browser, { viewport: { width: 1280, height: 860 } });
await signIn(pro, "professional");
await pro.goto(`${BASE}/dashboard`, { waitUntil: "networkidle" }); await shot(pro, "07_pro_overview");
await pro.goto(`${BASE}/dashboard/cases`, { waitUntil: "networkidle" }); await shot(pro, "08_pro_cases", true);
const link = await pro.$('a[href*="/dashboard/cases/"]');
if (link) { await link.click(); await pro.waitForLoadState("networkidle"); await shot(pro, "09_pro_case_detail", true); }
const admin = await newPage(browser, { viewport: { width: 1280, height: 860 } });
await signIn(admin, "admin");
await admin.goto(`${BASE}/dashboard`, { waitUntil: "networkidle" }); await shot(admin, "10_admin_overview", true);
await admin.goto(`${BASE}/dashboard/admin/matching`, { waitUntil: "networkidle" }); await shot(admin, "11_admin_matching", true);
console.log("report", rep.report_id);
await browser.close();
