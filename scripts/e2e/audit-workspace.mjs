import { BASE, launch, newPage, signIn, check, summary } from "./lib.mjs";
const browser = await launch();
const page = await newPage(browser, { viewport: { width: 1280, height: 860 } });
await signIn(page, "admin");
const ready = () => page.waitForFunction(() => !document.querySelector(".animate-pulse"), null, { timeout: 45000 }).catch(() => {});
await page.goto(BASE + "/dashboard/admin", { waitUntil: "domcontentloaded", timeout: 120000 }); await ready();
const open = async () => { await page.locator("header button, aside button").filter({ hasText: /Admin|Professional|E2E/ }).first().click().catch(() => {}); await page.waitForTimeout(600); };
const trigger = page.getByText("E2E", { exact: true }).first();
await trigger.click(); await page.waitForTimeout(800);
const radios = page.getByRole("radio");
check("workspace menu lists three workspaces", (await radios.count()) === 3, `n=${await radios.count()}`);
check("admin is marked current on /dashboard/admin", (await page.getByRole("radio", { name: /Admin/ }).getAttribute("aria-checked")) === "true");
await page.getByRole("radio", { name: /Mjengo suite/ }).click();
await page.waitForURL(/\/dashboard\/mjengo/, { timeout: 60000 }).catch(() => {});
check("choosing Mjengo goes to the suite", /\/dashboard\/mjengo/.test(page.url()), page.url());
await page.goto(BASE + "/dashboard", { waitUntil: "domcontentloaded", timeout: 120000 }); await ready(); await page.waitForTimeout(1500);
check("typing /dashboard in the same session is respected (no bounce)", new URL(page.url()).pathname === "/dashboard", page.url());
await page.evaluate(() => sessionStorage.clear());
await page.goto(BASE + "/dashboard/admin", { waitUntil: "domcontentloaded", timeout: 120000 }); await ready();
await page.evaluate(() => sessionStorage.clear());
await page.goto(BASE + "/dashboard", { waitUntil: "domcontentloaded", timeout: 120000 });
await page.waitForURL(/\/dashboard\/admin/, { timeout: 30000 }).catch(() => {});
check("a new session reopens in the last workspace (admin)", /\/dashboard\/admin/.test(page.url()), page.url());
await browser.close();
summary();
